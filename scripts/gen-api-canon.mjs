#!/usr/bin/env node
/**
 * Inlines a compact canon table into api/hourly.ts.
 *
 * Vercel does not bundle imports for functions in api/ -- not even relative
 * ones inside api/ itself (verified: both `../src/...` and `./_lib/...` fail at
 * runtime with ERR_MODULE_NOT_FOUND). The function therefore has to be a
 * single self-contained file, which would normally mean hand-copying the canon
 * and letting it drift. This script generates it from the real source instead,
 * so src/data/ethiopianCanon.ts stays the single point of truth.
 *
 *   npm run gen:api-canon
 */

import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const TARGET = path.join(ROOT, 'api/hourly.ts');
const START = '// <generated-canon>';
const END = '// </generated-canon>';

const canon = await import(path.join(ROOT, 'src/data/ethiopianCanon.ts'));

const compact = canon.ETHIOPIAN_CANON.map((book) => ({
  i: book.id,
  n: book.name,
  g: book.geezName ?? undefined,
  s: book.section,
  t: book.testament,
  p: book.parts
    // 'local' parts are transcribed files under src/data/texts, which the
    // self-contained function cannot import. Excluding them here keeps the
    // server's selection pool identical to the browser fallback's.
    .filter((part) => part.source === 'bible-api' || part.source === 'jsdelivr')
    .map((part) =>
      part.source === 'bible-api'
        ? { k: 'a', b: part.bookId, l: part.label, c: part.chapters }
        : { k: 'g', b: part.abbrev, l: part.label, c: part.chapters, e: part.english },
    ),
})).filter((book) => book.p.length > 0);

const body = `${START}\n// Generated by scripts/gen-api-canon.mjs from src/data/ethiopianCanon.ts.\n// Do not edit by hand; run \`npm run gen:api-canon\` after changing the canon.\nconst CANON: CompactBook[] = ${JSON.stringify(compact, null, 2)};\n${END}`;

const source = await fs.readFile(TARGET, 'utf8');
const from = source.indexOf(START);
const to = source.indexOf(END);
if (from === -1 || to === -1) {
  throw new Error(`Markers ${START} / ${END} not found in api/hourly.ts`);
}

await fs.writeFile(TARGET, source.slice(0, from) + body + source.slice(to + END.length));

const chapters = compact.reduce((sum, b) => sum + b.p.reduce((s, p) => s + p.c, 0), 0);
console.log(`Inlined ${compact.length} books / ${chapters} chapters into api/hourly.ts`);
